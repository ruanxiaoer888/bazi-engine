seed_rules = seed['rules']
seed_ids = {r['id'] for r in seed_rules}

new_rules = []
def add(rid, cat, cond, concl, src, conf='中', sug=None):
    if rid in seed_ids:
        print('SKIP (exists):', rid)
        return
    r = {'id': rid, 'category': cat, 'condition': cond,
         'conclusion': concl, 'source': src, 'confidence': conf}
    if sug:
        r['suggestion'] = sug
    new_rules.append(r)
    seed_ids.add(rid)


def main():
    with open(DB, 'r', encoding='utf-8') as f:
        db = json.load(f)
    rules = db['rules']
    by_id = {r['id']: r for r in rules}
    # 校验：所有 id 必须存在
    missing_id = [rid for rid in SUG if rid not in by_id]
    if missing_id:
        print('❌ 断语库中不存在的 id:', missing_id)
        sys.exit(1)
    # 校验：只补缺失的
    already = [rid for rid in SUG if by_id[rid].get('suggestion')]
    if already:
        print('⚠️ 已有 suggestion 将被跳过:', already)
    n = 0
    for rid, sug in SUG.items():
        r = by_id[rid]
        if not r.get('suggestion'):
            r['suggestion'] = sug
            n += 1
    # 校验：写完后应无缺失
    remain = [r['id'] for r in rules if not r.get('suggestion')]
    if remain:
        print('❌ 仍有缺失 suggestion:', remain)
        sys.exit(1)
    with open(DB, 'w', encoding='utf-8') as f:
        json.dump(db, f, ensure_ascii=False, indent=2)
    print(f'✅ 写入 {n} 条 suggestion，断语库总规则数 {len(rules)}，缺失 suggestion 清零')

if __name__ == '__main__':
    main()
